#!/bin/sh
set -eu

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
BODY="$ROOT/integrations/shared/dots-gate.body.md"

write_adapter() {
  _out="$1"
  _header="$2"
  mkdir -p "$(dirname "$_out")"
  printf '%s\n\n' "$_header" > "$_out"
  cat "$BODY" >> "$_out"
  printf 'rendered %s\n' "${_out#$ROOT/}"
}

write_adapter "$ROOT/integrations/opencode/AGENTS.md" "$(cat <<'EOF'
<!--
Generated by dotS from integrations/shared/dots-gate.body.md.
Installed as ~/.config/opencode/AGENTS.md when no global file exists.
Edit the shared source, not this file.
Regenerate with: sh integrations/shared/render-gate.sh
-->
EOF
)"

write_adapter "$ROOT/integrations/claude-code/CLAUDE.md" "$(cat <<'EOF'
<!--
Generated by dotS from integrations/shared/dots-gate.body.md.
Installed as ~/.claude/CLAUDE.md.
Edit the shared source, not this file.
Regenerate with: sh integrations/shared/render-gate.sh
-->
EOF
)"

write_adapter "$ROOT/integrations/generic/AGENTS.md" "$(cat <<'EOF'
<!--
Generated by dotS from integrations/shared/dots-gate.body.md.
Use as AGENTS.md in tools that accept markdown agent instructions.
Edit the shared source, not this file.
Regenerate with: sh integrations/shared/render-gate.sh
-->
EOF
)"

write_adapter "$ROOT/integrations/antigravity/rules/dots.md" "$(cat <<'EOF'
<!--
Generated by dotS from integrations/shared/dots-gate.body.md.
Installed as ~/.gemini/config/rules/dots.md and ~/.gemini/config/GEMINI.md.
Edit the shared source, not this file.
Regenerate with: sh integrations/shared/render-gate.sh
-->
EOF
)"

write_adapter "$ROOT/integrations/cursor/dots.mdc" "$(cat <<'EOF'
---
description: dotS routing gate — conditional routing with `skip dots` bypass
alwaysApply: true
---

<!--
Generated by dotS from integrations/shared/dots-gate.body.md.
Installed as ~/.cursor/rules/dots.mdc.
Edit the shared source, not this file.
Regenerate with: sh integrations/shared/render-gate.sh
-->
EOF
)"

write_adapter "$ROOT/integrations/hermes/skills/dots/SKILL.md" "$(cat <<'EOF'
---
name: dots
description: >-
  dotS routing gate with `skip dots` bypass. Use before web search or
  speculation on infrastructure, system configuration, and supported stacks.
---

<!--
Generated by dotS from integrations/shared/dots-gate.body.md.
Installed as a Hermes skill with its enablement notes.
Edit the shared source, not this file.
Regenerate with: sh integrations/shared/render-gate.sh
-->
EOF
)"
